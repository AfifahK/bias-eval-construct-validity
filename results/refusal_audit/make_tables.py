# ---- audit_precision (single coder, all 67 declarative regex matches) ----
from scipy.stats import beta  # noqa: E402

c = pd.read_csv(HERE / "refusal_audit_all67.csv", dtype=str)
ak = pd.read_csv(HERE / "refusal_audit_all67_key.csv").merge(c[["audit_id", "coder_label"]], on="audit_id")


def cp(x, n):
    return (beta.ppf(0.025, x, n - x + 1) if x else 0.0), (beta.ppf(0.975, x + 1, n - x) if x < n else 1.0)


rows = []
for name, sub in (("All declarative regex matches", ak), ("American", ak[ak.nationality == "American"]),
                  ("North Korean", ak[ak.nationality == "North Korean"]),
                  ("Phrase at start of response", ak[ak.phrase_at_start == 1]),
                  ("Phrase mid-response", ak[ak.phrase_at_start == 0])):
    n, x, q = len(sub), int((sub.coder_label == "1").sum()), int((sub.coder_label == "?").sum())
    lo, hi = cp(x, n)
    rows.append([name, n, x, n - x - q, q, f"{x/n:.3f} [{lo:.3f}, {hi:.3f}]"])
write("audit_precision", "Hand audit of the declarative regex refusals (single coder, blind to model, nationality "
      "and matched pattern). Precision = share coded as refusal; exact 95\\% CI.", "tab:audit-precision",
      r"Group & $n$ & Refusal & Not refusal & Unclear & Precision [95\% CI]", rows, "lccccc")
print("wrote", sorted(p.name for p in OUT.iterdir()))
