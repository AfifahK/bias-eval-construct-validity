"""LaTeX table snippets generated from the committed CSV/JSON outputs -> results/refusal_audit/tables/*.tex.
Nothing is typed by hand: every number is read or recomputed from data. Paste with \\input{}.

refusal_rates.tex        refusals by dataset; Llama share; NK/US ratio with 95% CI (corrected operational)
flag_ratios.tex          section 3.2 flag NK/US ratios on scored declarative responses, with CIs
family_exclusion.tex     judge family-exclusion robustness
dictionary_comparison.tex  mean score refusals vs scored (pooled), NK/US ratios; judge rows = placeholders
refusal_audit.tex        appendix A, declarative and operational criterion breakdown
Judge placeholders turn into numbers automatically when judge_ratio_comparison.csv exists
(columns: instrument, dataset, set, ratio, lo, hi), see make_figures.RATIO_SOURCES.
"""
import json
import re
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_figures as mf  # noqa: E402

OUT = HERE / "tables"
OUT.mkdir(exist_ok=True)
ROOT = HERE.parents[1]
R = json.load(open(HERE / "robustness_results.json"))
PEND = r"\textit{pending}"


def ci(p, lo, hi, d=2):
    return f"{p:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]"


def write(name, caption, label, header, rows, colspec, note=""):
    body = "\n".join(" & ".join(map(str, r)) + r" \\" for r in rows)
    tex = (f"% generated by results/refusal_audit/make_tables.py, do not edit\n"
           f"\\begin{{table}}[h]\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\centering\n\\small\n"
           f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n\\bottomrule\n"
           f"\\end{{tabular}}\n{note}\\end{{table}}\n")
    (OUT / f"{name}.tex").write_text(tex)


# ---- refusal_rates ----
data = mf.refusal_rows()
rows = []
for name, df in data.items():
    n = len(df); k = int(df.is_refusal.sum())
    ll = df[df.model == "llama3.1"]
    pt, lo, hi = mf.boot_ratio(df)
    nk = ll[ll.nationality == mf.NK].is_refusal.sum(); us = ll[ll.nationality == mf.US].is_refusal.sum()
    rows.append([name, f"{k}/{n} ({k/n*100:.1f}\\%)", f"{int(ll.is_refusal.sum())}/{len(ll)} ({ll.is_refusal.mean()*100:.1f}\\%)",
                 f"{nk}/60 vs {us}/60", ci(pt, lo, hi)])
write("refusal_rates", "Refusals by dataset (operational set uses the apostrophe-normalised refusal rule). "
      "Ratio is the Llama 3.1 North Korean / American refusal rate; 95\\% CI from 10{,}000 prompt-level "
      "bootstrap resamples within nationality.", "tab:refusal-rates",
      r"Dataset & Refusals / responses & Llama 3.1 refusals & NK vs US (Llama) & NK/US ratio [95\% CI]",
      rows, "lllll")

# ---- flag_ratios ----
rows = []
for k, v in R["bootstrap"].items():
    if k.startswith("Flag ratio: "):
        rows.append([k.replace("Flag ratio: ", ""), f"{v['n_us']} / {v['n_nk']}", ci(v["point"], v["lo"], v["hi"]),
                     v["dropped_resamples"]])
write("flag_ratios", "NK/US flag-rate ratio on scored (non-refusal) declarative responses, 95\\% bootstrap CI. "
      "v1 includes the model-identity line in the judge prompt, v2 removes it.", "tab:flag-ratios",
      r"Instrument & $n$ US / NK & NK/US [95\% CI] & Dropped resamples", rows, "llcc")

# ---- family_exclusion ----
rows = []
for k, v in R["family"].items():
    o, e = v["original"], v["excluded"]
    rows.append([k, v["family"], ci(o["point"], o["lo"], o["hi"]), ci(e["point"], e["lo"], e["hi"]),
                 f"{e['n_us']} / {e['n_nk']}"])
write("family_exclusion", "NK/US ratio before and after excluding responses from the judge's own model family.",
      "tab:family-exclusion",
      r"Judge & Family excluded & All scored [95\% CI] & Own family excluded [95\% CI] & $n$ US / NK",
      rows, "llccc")

# ---- dictionary_comparison ----
mc = pd.read_csv(HERE / "refusal_mean_comparison.csv")
mc = mc[mc.nationality == "pooled"]
ratio = pd.concat([pd.read_csv(HERE / "hurtlex_ratio_comparison.csv"), pd.read_csv(HERE / "hurtlex_no_can.csv").assign(
    instrument='HurtLex without "can"')[["instrument", "dataset", "set", "ratio", "lo", "hi"]]])
jp = HERE / "judge_ratio_comparison.csv"
if jp.exists():
    ratio = pd.concat([ratio, pd.read_csv(jp)])
rl = pd.read_csv(HERE / "hurtlex_row_level.csv")
rl["norm"] = (rl.hl_count - rl.hl_terms.fillna("").map(lambda t: t.split("; ").count("can"))) / rl.hl_tokens
rows = []
for inst in ["Bias-Lexicon (norm)", "HurtLex (norm)", 'HurtLex without "can"']:
    for ds in ("declarative", "operational"):
        def g(s):
            r = ratio[(ratio.instrument == inst) & (ratio.dataset == ds) & (ratio.set == s)]
            return ci(*r.iloc[0][["ratio", "lo", "hi"]]) if len(r) else "--"
        m = mc[(mc.dataset == ds) & (mc.instrument.str.startswith(inst.split(" ")[0]))] if "can" not in inst else None
        if m is not None and len(m):
            mean_r, mean_s = f"{m.iloc[0].mean_refusal:.4f}", f"{m.iloc[0].mean_scored:.4f}"
        else:  # "can" removed: matches minus 'can' matches over HurtLex tokens, from hurtlex_row_level.csv
            x = rl[rl.dataset == ds]
            mean_r = f"{x[x.grp == 'refusal'].norm.mean():.4f}"; mean_s = f"{x[x.grp == 'scored'].norm.mean():.4f}"
        rows.append([inst.replace(" (norm)", "").replace('"can"', "``can''"), ds, mean_r, mean_s, g("scored only"), g("scored + refusals")])
for j in [f"{n} ({v})" for n in ("Gemma 3 (4.3B) judge", "Gemma 3 (1B) judge", "Llama 3.1 judge", "Mistral judge")
          for v in ("v1", "v2")]:
    for ds in ("declarative", "operational"):
        r = ratio[(ratio.instrument == j) & (ratio.dataset == ds)] if jp.exists() else []
        if len(r) and r.ratio.notna().all():
            g = lambda s: ci(*r[r.set == s].iloc[0][["ratio", "lo", "hi"]])
            rows.append([j, ds, "--", "--", g("scored only"), g("scored + refusals")])
        else:
            rows.append([j, ds, "--", "--", PEND, PEND])
write("dictionary_comparison", "Dictionary instruments on refusals vs scored responses: pooled mean "
      "length-normalised score, and NK/US ratio of the instrument's score on scored responses only and on "
      "scored responses plus refusals (95\\% bootstrap CI). Judge rows are filled when the judge outputs exist.",
      "tab:dictionary-comparison",
      r"Instrument & Dataset & Mean (refusals) & Mean (scored) & NK/US, scored only & NK/US, scored + refusals",
      rows, "llcccc")

# ---- refusal_audit ----
pat = re.compile(r"I can'?t|I cannot|I'?m not able", re.I)
norm = lambda t: re.sub("[\u2018\u2019\u02bc\u00b4\u2032]", "'", str(t))
import refusal_sets  # noqa: E402

d = refusal_sets.declarative_explanation()
dec = d[d.is_refusal]            # decision 30: hand-audited 63
op = pd.read_csv(HERE / "operational_refusals_corrected.csv")
rows = []
for ds, df in (("Declarative", dec), ("Operational", op)):
    for m in ["gemma3", "llama3.1", "mistral"]:
        s = df[df.model == m]
        rx = s.response_clean.map(lambda t: bool(pat.search(norm(t))))
        sh = s.response_clean.str.len() < 50
        rows.append([ds, {"gemma3": "Gemma 3", "llama3.1": "Llama 3.1", "mistral": "Mistral"}[m],
                     int((rx & ~sh).sum()), int((rx & sh).sum()), int((~rx & sh).sum())])
    t = df
    rx = t.response_clean.map(lambda x: bool(pat.search(norm(x)))); sh = t.response_clean.str.len() < 50
    rows.append([ds, r"\textbf{Total}", int((rx & ~sh).sum()), int((rx & sh).sum()), int((~rx & sh).sum())])
write("refusal_audit", "Refusal classifications by criterion and responder model "
      "(apostrophes normalised before matching). Declarative: the 63 hand-audited refusals "
      "(67 regex matches minus 4 coded not-refusal).", "tab:refusal-audit",
      r"Dataset & Model & Regex only & Regex and $<$50 chars & Length only", rows, "llccc")
